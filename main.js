function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
}

// navbar + footer
function renderChrome() {
  const page = document.body.dataset.page;
  const links = [
    { name: "home", href: "index.html" },
    { name: "about", href: "about.html" },
    { name: "projects", href: "projects.html" },
  ];

  document.getElementById("navbar").innerHTML = `
    <a href="index.html" class="navbar-brand">${CONFIG.name}</a>
    <div class="navbar-links">
      ${links
        .map((l) => `<a href="${l.href}" class="navbar-link${l.name === page ? " navbar-link-active" : ""}">${l.name}</a>`)
        .join("")}
    </div>`;

  document.getElementById("footer").innerHTML = `
    <span class="footer-text">
      made with ❤️ by ${CONFIG.name}
    </span>`;

  document.querySelectorAll("[data-icon]").forEach((el) => {
    el.innerHTML = ICONS[el.dataset.icon] || "";
  });
}

// discord card: click copies the username (Discord has no public profile links by username)
function setupDiscordCard() {
  const card = document.getElementById("discord-card");
  if (!card) return;

  const hint = card.querySelector(".discord-card-hint");
  card.addEventListener("click", async () => {
    try {
      await navigator.clipboard.writeText(CONFIG.discord);
      hint.textContent = "copied!";
    } catch {
      hint.textContent = CONFIG.discord;
    }
    setTimeout(() => (hint.textContent = "click to copy"), 2000);
  });
}

// projects pulled live from GitHub's public API
async function loadProjects() {
  const container = document.getElementById("project-container");
  if (!container) return;

  try {
    const res = await fetch(`https://api.github.com/users/${CONFIG.github}/repos?sort=updated&per_page=100`);
    if (!res.ok) throw new Error(`GitHub API returned ${res.status}`);

    const repos = (await res.json()).filter(
      (r) => !r.fork && r.name.toLowerCase() !== CONFIG.github.toLowerCase(),
    );

    if (repos.length === 0) {
      container.innerHTML = `<p class="project-empty">No public projects yet, check back soon!</p>`;
      return;
    }

    container.innerHTML = repos
      .map(
        (r) => `
      <a class="project-card" href="${escapeHtml(r.html_url)}" target="_blank" rel="noreferrer">
        <span class="project-icon">${ICONS.external}</span>
        <h3 class="project-title">${escapeHtml(r.name)}</h3>
        <p class="project-description">${escapeHtml(r.description || "No description")}</p>
        <div class="project-bottom-container">
          <span class="project-lang">
            <div class="project-lang-dot" style="background-color:${LANGUAGE_COLORS[r.language] || "#d4cdcd"}"></div>
            ${escapeHtml(r.language || "Unknown")}
          </span>
          <div class="project-stars">${ICONS.star}<span>${r.stargazers_count}</span></div>
          <div class="project-forks">${ICONS.fork}<span>${r.forks_count}</span></div>
        </div>
      </a>`,
      )
      .join("");
  } catch (err) {
    console.error(err);
    container.innerHTML = `<p class="project-empty">Couldn't load projects right now.</p>`;
  }
}

renderChrome();
